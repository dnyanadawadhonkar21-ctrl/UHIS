const analyzeSymptoms = async (req, res, next) => {
  try {
    const { symptoms = [], feverDuration, severity = 5, age = 30 } = req.body;

    if (!Array.isArray(symptoms) || symptoms.length === 0) {
      return res.status(400).json({ success: false, message: 'Please select or list at least one symptom.' });
    }

    const symptomsLower = symptoms.map((s) => s.toLowerCase());

    let possibleConditions = [];
    let riskLevel = 'LOW';
    let triageAdvice = 'Maintain hydration and observe for 24-48 hours. Consult a general physician if symptoms persist.';
    let riskScore = 25;

    if (symptomsLower.includes('chest pain') || symptomsLower.includes('shortness of breath')) {
      riskLevel = 'HIGH (CRITICAL)';
      riskScore = 88;
      triageAdvice = 'IMMEDIATE MEDICAL ATTENTION REQUIRED: Proceed to the nearest emergency OPD or cardiology unit.';
      possibleConditions = [
        { disease: 'Acute Coronary Syndrome / Angina', probability: '82%', urgency: 'EMERGENCY' },
        { disease: 'Pulmonary Embolism', probability: '64%', urgency: 'EMERGENCY' },
      ];
    } else if (symptomsLower.includes('fever') && symptomsLower.includes('cough') && symptomsLower.includes('fatigue')) {
      riskLevel = 'MODERATE';
      riskScore = 62;
      triageAdvice = 'Schedule a consultation with a General Physician and order a Complete Blood Count (CBC) & COVID/Influenza test.';
      possibleConditions = [
        { disease: 'Viral Upper Respiratory Infection', probability: '78%', urgency: 'OPD' },
        { disease: 'Bacterial Pneumonia', probability: '45%', urgency: 'OPD' },
        { disease: 'Influenza Type A/B', probability: '69%', urgency: 'OPD' },
      ];
    } else if (symptomsLower.includes('headache') && symptomsLower.includes('nausea')) {
      riskLevel = 'LOW-MODERATE';
      riskScore = 38;
      triageAdvice = 'Rest in a quiet room, stay hydrated. Consult doctor if vision changes or neck stiffness occur.';
      possibleConditions = [
        { disease: 'Migraine / Tension Headache', probability: '74%', urgency: 'ROUTINE' },
        { disease: 'Dehydration / Electrolyte Imbalance', probability: '55%', urgency: 'ROUTINE' },
      ];
    } else {
      possibleConditions = [
        { disease: 'General Malaise / Mild Viral Response', probability: '65%', urgency: 'ROUTINE' },
      ];
    }

    res.status(200).json({
      success: true,
      aiAnalysis: {
        analyzedSymptoms: symptoms,
        riskScore,
        riskLevel,
        triageAdvice,
        possibleConditions,
        recommendedSpecialist: riskScore > 70 ? 'Cardiologist / Emergency Specialist' : 'General Physician',
        disclaimer: 'This AI recommendation is generated by the UHIS Predictive ML Model and does not replace professional clinical diagnosis.',
      },
    });
  } catch (error) {
    next(error);
  }
};

const calculateHealthRiskScore = async (req, res, next) => {
  try {
    const { age = 45, bmi = 26.5, systolicBp = 135, glucose = 110, smoker = false, familyHistory = true } = req.body;

    let score = 20;
    if (age > 40) score += 15;
    if (age > 60) score += 15;
    if (bmi > 25) score += 10;
    if (bmi > 30) score += 15;
    if (systolicBp > 130) score += 15;
    if (systolicBp > 140) score += 10;
    if (glucose > 100) score += 10;
    if (glucose > 126) score += 15;
    if (smoker) score += 20;
    if (familyHistory) score += 10;

    const normalizedScore = Math.min(Math.max(score, 5), 98);

    const breakdown = {
      cardiovascularRisk: Math.min(normalizedScore + 5, 95),
      diabetesRisk: glucose > 100 ? 68 : 22,
      hypertensionRisk: systolicBp > 130 ? 72 : 18,
      lifestyleScore: smoker ? 40 : 85,
    };

    res.status(200).json({
      success: true,
      healthScore: {
        overallRiskIndex: normalizedScore,
        category: normalizedScore > 70 ? 'HIGH RISK' : normalizedScore > 40 ? 'MODERATE RISK' : 'HEALTHY / LOW RISK',
        breakdown,
        aiRecommendations: [
          'Schedule annual cardiac screening (ECG & Lipid Profile).',
          'Maintain 150 minutes of moderate aerobic activity weekly.',
          'Adopt low-sodium DASH diet guidelines.',
        ],
      },
    });
  } catch (error) {
    next(error);
  }
};

const classifyMedicalReport = async (req, res, next) => {
  try {
    const { reportText = '' } = req.body;

    let predictedCategory = 'GENERAL_REPORT';
    let keyEntities = [];
    let confidence = 0.89;

    const textLower = reportText.toLowerCase();
    if (textLower.includes('hemoglobin') || textLower.includes('wbc') || textLower.includes('platelet')) {
      predictedCategory = 'PATHOLOGY_CBC';
      keyEntities = ['Hemoglobin', 'Leukocyte Count (WBC)', 'Platelets'];
      confidence = 0.96;
    } else if (textLower.includes('x-ray') || textLower.includes('opacity') || textLower.includes('mri') || textLower.includes('ct scan')) {
      predictedCategory = 'RADIOLOGY_IMAGING';
      keyEntities = ['Lung Parenchyma', 'Radiopaque Shadow', 'Intervertebral Disc'];
      confidence = 0.94;
    } else if (textLower.includes('glucose') || textLower.includes('hba1c') || textLower.includes('creatinine')) {
      predictedCategory = 'BIOCHEMISTRY_METABOLIC';
      keyEntities = ['Fasting Blood Sugar', 'Serum Creatinine', 'HbA1c'];
      confidence = 0.97;
    }

    res.status(200).json({
      success: true,
      nlpClassification: {
        predictedCategory,
        confidenceScore: `${(confidence * 100).toFixed(1)}%`,
        extractedEntities: keyEntities,
        summary: reportText ? `Extracted ${keyEntities.length} medical parameters from document snippet.` : 'Sample report classified.',
      },
    });
  } catch (error) {
    next(error);
  }
};

